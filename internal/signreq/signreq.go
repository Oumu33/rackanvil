// Package signreq implements HMAC-SHA256 request signing for the agent
// protocol (M11).
//
// Why: the vendor's PXE-stage heartbeat (recovered in M10) protects its
// liveness signal with a runtime salt + nonce + signature envelope, while
// its post-install agent reports in cleartext with only a bearer token —
// anyone who learns or guesses a token can forge checkins, task reports
// and metrics for that host. Our agent protocol adopts the good half of
// the vendor design (per-host key + timestamp + nonce + signature) with
// a standard construction:
//
//   - key: 32 random bytes, generated by the server and issued exactly
//     once per enrollment via the initialize response (never baked into
//     any image, never shared between hosts);
//   - signature: hex HMAC-SHA256 over the canonical string
//     hostID \n method \n path \n unix-ts \n nonce \n sha256hex(body);
//   - freshness: server rejects timestamps more than MaxSkew from its
//     clock and remembers nonces for the skew window (replay cache), so
//     a captured request cannot be re-sent later or twice.
//
// Enrollment itself (initialize) is unsigned by necessity — it is the
// bootstrap that issues the key — and keeps the pre-existing controls
// (it only creates/rotates credentials for a MAC identity).
package signreq

import (
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
)

// MaxSkew is the accepted clock difference between agent and server.
const MaxSkewSeconds = 120

// NewKey returns a fresh random signing key, hex-encoded.
func NewKey() (string, error) {
	var b [32]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", err
	}
	return hex.EncodeToString(b[:]), nil
}

// NewNonce returns a fresh random nonce, hex-encoded.
func NewNonce() (string, error) {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", err
	}
	return hex.EncodeToString(b[:]), nil
}

// BodyHash is the sha256 of the raw request body, hex-encoded.
func BodyHash(body []byte) string {
	sum := sha256.Sum256(body)
	return hex.EncodeToString(sum[:])
}

// canonical is the single definition of what gets signed. Both sides
// (agent client, API server) must build it identically.
func canonical(keyHostID, method, path string, ts int64, nonce string, body []byte) []byte {
	return []byte(fmt.Sprintf("%s\n%s\n%s\n%d\n%s\n%s",
		keyHostID, method, path, ts, nonce, BodyHash(body)))
}

// Sign computes the request signature for the given parts.
func Sign(keyHex, hostID, method, path string, ts int64, nonce string, body []byte) (string, error) {
	key, err := hex.DecodeString(keyHex)
	if err != nil {
		return "", fmt.Errorf("signreq: bad key: %w", err)
	}
	mac := hmac.New(sha256.New, key)
	mac.Write(canonical(hostID, method, path, ts, nonce, body))
	return hex.EncodeToString(mac.Sum(nil)), nil
}

// Verify reports whether sig is the valid signature for the parts.
// Comparison is constant-time.
func Verify(keyHex, hostID, method, path string, ts int64, nonce string, body []byte, sig string) bool {
	want, err := Sign(keyHex, hostID, method, path, ts, nonce, body)
	if err != nil {
		return false
	}
	return hmac.Equal([]byte(want), []byte(sig))
}
